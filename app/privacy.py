"""B(통합): 외부 AI(OpenAI)로 보내는 자유 문장에서 사람을 특정하는 번호를 가린다.

모양이 정해진 것만 정규식으로 가린다: 이메일, 주민등록번호·외국인등록번호, 전화번호, 차량번호.
이름·주소는 모양이 정해져 있지 않아 가리지 못한다(입력 화면에서 적지 않게 안내한다).
어디서 무엇을 보내는지는 docs/external-data-transfer.md에 있다.
"""

import re

_EMAIL = re.compile(r"[A-Za-z0-9._%+-]+@[A-Za-z0-9-]+(?:\.[A-Za-z0-9-]+)*\.[A-Za-z]{2,}")
# 생년월일 6자리 + 성별 자리(1~8) + 6자리. 가운데 하이픈은 없어도 된다
_RESIDENT_NUMBER = re.compile(
    r"(?<!\d)\d{2}(?:0[1-9]|1[0-2])(?:0[1-9]|[12]\d|3[01])\s?[-–]?\s?[1-8]\d{6}(?!\d)"
)
# 휴대폰(010 등, +82로 시작해도 된다)과 지역번호·인터넷 전화(02, 031~064, 070).
# 구분자는 - . 공백이고 없어도 된다. 날짜(2026-11-16)는 0으로 시작하지 않아 걸리지 않는다
_PHONE = re.compile(
    r"(?<![\d+])(?:\+82[-.\s]?|0)1[016789][-.\s]?\d{3,4}[-.\s]?\d{4}(?!\d)"
    r"|(?<!\d)0(?:2|[3-6][1-5]|70)\)?[-.\s]?\d{3,4}[-.\s]?\d{4}(?!\d)"
)
# 차량번호: 숫자 2~3자리 + 용도 글자 + 숫자 4자리(12가3456, 123가 4567). 지역명이 앞에 붙은
# 예전 번호(서울12가3456)는 이 부분이 가려진다. 용도 글자만 받으므로 '10시 1234'·'20대 1234'는
# 걸리지 않는다. '12도 3456'처럼 용도 글자와 같은 글자가 오면 차량번호로 가려진다
# (덜 가리는 쪽보다 낫다)
_PLATE_LETTERS = "가나다라마거너더러머버서어저고노도로모보소오조구누두루무부수우주아바사자배하허호"
_PLATE = re.compile(rf"(?<!\d)\d{{2,3}}\s?[{_PLATE_LETTERS}]\s?\d{{4}}(?!\d)")

# 이메일 안의 숫자가 다른 규칙에 먼저 걸리지 않게 이메일부터,
# 13자리 주민등록번호를 전화번호보다 먼저 가린다
_RULES = (
    (_EMAIL, "[이메일]"),
    (_RESIDENT_NUMBER, "[주민등록번호]"),
    (_PHONE, "[전화번호]"),
    (_PLATE, "[차량번호]"),
)


def mask_identifiers(text: str) -> str:
    """이메일·주민등록번호·전화번호·차량번호를 [이메일] 같은 표시로 바꾼다. 나머지 글은 그대로다."""
    for pattern, label in _RULES:
        text = pattern.sub(label, text)
    return text
