"""B: 외부 AI로 보내는 글의 번호 가리기(app/privacy.py)."""

import pytest

from app.privacy import mask_identifiers


@pytest.mark.parametrize(("text", "masked"), [
    ("연락처 010-1234-5678", "연락처 [전화번호]"),
    ("01098765432로 전화", "[전화번호]로 전화"),
    ("+82 10 1234 5678", "[전화번호]"),
    ("사무실 02-123-4567", "사무실 [전화번호]"),
    ("031.123.4567", "[전화번호]"),
    ("070-1234-5678", "[전화번호]"),
    ("900101-1234567", "[주민등록번호]"),
    ("9001011234567", "[주민등록번호]"),
    ("외국인 900101-5234567", "외국인 [주민등록번호]"),
    ("상대 차 12가3456", "상대 차 [차량번호]"),
    ("123가 4567", "[차량번호]"),
    ("서울12가3456", "서울[차량번호]"),
    ("렌터카 12 하 3456", "렌터카 [차량번호]"),
    ("kim.lee+claim@example.co.kr로 보내 주세요", "[이메일]로 보내 주세요"),
    ("차주 010-1234-5678, 12가3456", "차주 [전화번호], [차량번호]"),
])
def test_masks_identifiers(text, masked):
    assert mask_identifiers(text) == masked


@pytest.mark.parametrize("text", [
    "사고 일자 2026-11-16 10:30",
    "손해액 4,500만 원, 45000000원",
    "제24조 ① 제5호, 별표3 1. 과실상계",
    "차31-1, 차4-2 도표",
    "서울 강남구 테헤란로 152, 대구 중구 국채보상로 123길 45",
    "10시 1234, 20대 운전자, 3차로 1234m",
    "대표번호 1588-1234",
])
def test_leaves_other_text_unchanged(text):
    assert mask_identifiers(text) == text
